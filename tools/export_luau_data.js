// Generates my-version/src/ReplicatedStorage/RoBikes/BikeData.luau from the user's extracted MX Bikes data.
// Only physics numbers are exported (no models, textures, sounds or code). Original key names are kept so
// every value traces back to its source file (see FINDINGS.md / REPORT.md for evidence IDs).
//
// usage: node export_luau_data.js <extracted bikes dir> <extracted tyres dir> <out .luau>
"use strict";
const fs = require("fs");
const path = require("path");
const { parseFile, curve } = require("./parse_piboso");

const [bikesDir, tyresDir, outFile] = process.argv.slice(2);
const BIKES = ["250x", "250xf", "350xf", "450xf", "450sm"];
const CFG_GROUPS = ["engine", "fueltank", "gearbox", "driveline", "wheel0", "wheel1", "chassis", "aero", "steer",
  "front_suspension", "rear_suspension", "autoclutch", "shifthelp", "wheelinghelp"];
const GEOM_KEYS = ["chassis_mass", "rakeangle_min", "front_length", "rear_length", "shock_minlength", "rider_mass",
  "fwheel", "rwheel_min", "rwheel_max", "rsusp_type"];
const TYRES = { mx: ["p_mx", "p_mx_f_midsoft.tyre", "p_mx_r_midsoft.tyre"],
                sm: ["m_sm", "m_sm_f_medium.tyre", "m_sm_r_medium.tyre"] };

function readIni(file) {
  const out = {};
  for (const line of fs.readFileSync(file, "latin1").split(/\r?\n/)) {
    const m = /^\s*([A-Za-z_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (m) out[m[1]] = isNaN(Number(m[2])) || m[2] === "" ? m[2] : Number(m[2]);
  }
  return out;
}

function luaKey(k) { return /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : `[${JSON.stringify(k)}]`; }
function toLuau(v, ind = "") {
  const next = ind + "\t";
  if (Array.isArray(v)) return "{ " + v.map((x) => toLuau(x, next)).join(", ") + " }";
  if (v && typeof v === "object") {
    const keys = Object.keys(v);
    if (!keys.length) return "{}";
    return "{\n" + keys.map((k) => `${next}${luaKey(k)} = ${toLuau(v[k], next)},`).join("\n") + `\n${ind}}`;
  }
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "0";
  return JSON.stringify(String(v));
}

const data = { bikes: {}, tyres: {}, surfaces: {}, provenance: {} };
for (const b of BIKES) {
  const dir = path.join(bikesDir, b);
  const cfg = parseFile(path.join(dir, b + ".cfg"));
  const engn = parseFile(path.join(dir, b + ".engn"));
  const geom = parseFile(path.join(dir, b + ".geom"));
  const ini = readIni(path.join(dir, b + ".ini"));
  const bike = { id: b, name: ini.name, info: { weight: ini.weight, max_power_kW: ini.max_power, gears: ini.gears,
    engine_type: ini.engine_type, tyres_type: ini.tyres_type } };
  for (const g of CFG_GROUPS) if (cfg[g]) bike[g] = cfg[g];
  bike.curves = { torque: curve(engn.torque), brake: curve(engn.brake) };
  bike.geom = {};
  for (const k of GEOM_KEYS) if (geom[k] !== undefined) bike.geom[k] = geom[k];
  data.bikes[b] = bike;
  data.provenance[b] = `bikes.pkz:bikes/${b}/${b}.cfg|.engn|.geom|.ini (REA ev_58e62a75)`;
}
for (const [type, [folder, f, r]] of Object.entries(TYRES)) {
  const front = parseFile(path.join(tyresDir, folder, f));
  const rear = parseFile(path.join(tyresDir, folder, r));
  const strip = (t) => { const o = { ...t }; delete o.compound0; delete o.compound1; delete o.compound2; return o; };
  data.tyres[type] = { front: strip(front), rear: strip(rear),
    compound: { front: front.compound0, rear: rear.compound0 } };
  data.provenance["tyres_" + type] = `tyres.pkz:tyres/${folder}/${f}, ${r} (REA ev_8f490ff3)`;
}
// Surface table (grip/resistance/compacting/bulldozing) from the MX rear tyre compound.
const comp = data.tyres.mx.compound.rear;
for (const [k, v] of Object.entries(comp)) if (v && typeof v === "object") data.surfaces[k] = v;

const header = `--!nocheck
-- AUTO-GENERATED by tools/export_luau_data.js from the user's own MX Bikes install (physics numbers only).
-- Do not edit by hand; re-run the exporter. Key names match the original files for traceability.
`;
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, header + "return " + toLuau(data) + "\n");
console.log("wrote", outFile, fs.statSync(outFile).size, "bytes; bikes:", Object.keys(data.bikes).join(","),
  "surfaces:", Object.keys(data.surfaces).length);
